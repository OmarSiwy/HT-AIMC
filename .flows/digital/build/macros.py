"""Analog hard macros of a digital top, declared once in build/macros.toml.

  python3 macros.py config <macros.toml> <config.yaml>  check ports, then rewrite the
                                                        generated block of a LibreLane config
  python3 macros.py sim    <macros.toml>                print the behavioural .v files (simulation)
  python3 macros.py check  <macros.toml>                behavioural model, blackbox and .subckt
                                                        must have the same ports
  python3 macros.py signoff <macros.toml> <run dir>     after a LibreLane run: DRC/LVS/XOR zero,
                                                        a GDS, only analog supplies left unconnected,
                                                        no cell but a macro on an analog net

Harden uses each macro's blackbox + gds/lef/lib, simulation uses its behavioural
model, so the two cannot disagree on ports without `check` failing. Stdlib only
(tomllib, Python >= 3.11): the plain `nix-shell -p iverilog yosys` shell can run it.
"""
import json
import os
import re
import sys
import tomllib
from pathlib import Path

BEGIN = "# >>> generated by build/macros.py from build/macros.toml, do not edit by hand"
END = "# <<< end generated"


def load(toml_path):
    toml_path = Path(toml_path).resolve()
    here = toml_path.parent
    decl = tomllib.loads(toml_path.read_text())
    root = (here / decl.get("analog_root", "../../../analog")).resolve()
    macros = []
    for m in decl.get("macro", []):
        b = m["block"]
        if m.get("todo"):
            print(f"macros.py: skipping {b} (TODO: {m['todo']})", file=sys.stderr)
            continue
        out = root / b / "output"
        views = {
            "gds": out / "gds" / f"{b}.gds",
            "lef": out / "lef" / f"{b}.lef",
            "lib": out / "lib" / f"{b}.lib",
            "blackbox": out / "verilog" / f"{b}.v",
            "behavioural": root / b / "va" / f"{b}_beh.v",
            "subckt": root / b / "netlist" / f"{b}.spice",
        }
        views.update({k: (here / v).resolve() for k, v in m.get("views", {}).items()})
        m["views"] = views
        macros.append(m)
    return macros


def need(m, view):
    p = m["views"][view]
    if not p.exists():
        sys.exit(f"macros.py: {m['block']}: missing {view} view {p}")
    return p


def strip(text):
    text = re.sub(r"/\*.*?\*/|\(\*.*?\*\)", " ", text, flags=re.S)
    # supply pins of a powered (USE_POWER_PINS) view are not signal ports
    text = re.sub(r"`ifdef\s+USE_POWER_PINS\b.*?`endif", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def verilog_ports(path, module):
    """{name: (direction, width)} from an ANSI-style module header."""
    hdr = re.search(
        rf"\bmodule\s+{module}\b\s*(?:#\s*\(.*?\)\s*)?\((.*?)\)\s*;", strip(path.read_text()), re.S
    )
    if not hdr:
        sys.exit(f"macros.py: {path}: no ANSI header for module {module}")
    ports, direction, width = {}, None, 1
    for item in hdr.group(1).split(","):
        toks = re.findall(r"\[[^\]]*\]|[\w$]+", item)
        if not toks:
            continue
        if toks[0] in ("input", "output", "inout"):
            direction, width = toks[0], 1  # a new direction resets the width
        rng = [t for t in toks if t.startswith("[")]
        if rng:
            msb, lsb = (int(x) for x in rng[0][1:-1].split(":"))
            width = abs(msb - lsb) + 1
        ports[toks[-1]] = (direction, width)
    return ports


def bits(ports):
    return {n if w == 1 else f"{n}[{i}]" for n, (_, w) in ports.items() for i in range(w)}


def subckt_ports(path, name):
    deck = re.sub(r"\n\+", " ", path.read_text())
    m = re.search(rf"^\s*\.subckt\s+{name}\s+([^\n]*)", deck, re.M | re.I)
    if not m:
        sys.exit(f"macros.py: {path}: no .subckt {name}")
    toks = [t for t in m.group(1).split() if "=" not in t]  # drop params
    return {re.sub(r"<(\d+)>", r"[\1]", t).lower() for t in toks}


def check(macros):
    ok = True
    for m in macros:
        b = m["block"]
        bb = verilog_ports(need(m, "blackbox"), b)
        beh = verilog_ports(need(m, "behavioural"), b)
        sub = subckt_ports(need(m, "subckt"), b)
        supplies = {p for pg in m.get("pg", []) for p in pg["pins"]} | set(m.get("analog_supplies", []))
        want = {p.lower() for p in bits(bb) | supplies}
        errs = []
        if bb != beh:
            errs.append(f"blackbox {sorted(bb.items())} != behavioural {sorted(beh.items())}")
        if sub != want:
            errs.append(f".subckt only {sorted(sub - want)}, blackbox+supplies only {sorted(want - sub)}")
        for e in errs:
            print(f"{b}: {e}")
        ok = ok and not errs
        if not errs:
            print(f"{b}: ports agree ({len(bb)} signal ports, {len(supplies)} supply pins)")
    if not ok:
        sys.exit("macros.py: port lists disagree")


def config_block(macros, cfg_dir):
    if not macros:
        return []
    rel = lambda p: "dir::" + os.path.relpath(p, cfg_dir)
    entries, pdn, nets = {}, [], []
    hx = hy = 0
    for m in macros:
        v = m["views"]
        e = {
            "gds": [rel(need(m, "gds"))],
            "lef": [rel(need(m, "lef"))],
            "vh": [rel(need(m, "blackbox"))],
            "instances": m["instances"],
        }
        if v["lib"].exists():
            e["lib"] = {"*": [rel(v["lib"])]}
        else:
            print(f"macros.py: {m['block']}: no .lib, STA sees a black box", file=sys.stderr)
        entries[m["block"]] = e
        for inst in m["instances"]:
            for pg in m.get("pg", []):
                pdn.append(" ".join([re.escape(inst), *pg["nets"], *pg["pins"]]))
        nets += m.get("analog_nets", [])
        x, y = m.get("halo", [0, 0])
        hx, hy = max(hx, x), max(hy, y)
    # JSON is YAML, so each value goes out as one flow-style line.
    out = {
        "MACROS": entries,
        "PDN_MACRO_CONNECTIONS": pdn,
        # LibreLane's halos are global, so the largest declared one wins.
        "FP_MACRO_HORIZONTAL_HALO": hx,
        "FP_MACRO_VERTICAL_HALO": hy,
        "PDN_HORIZONTAL_HALO": hx,
        "PDN_VERTICAL_HALO": hy,
    }
    if nets:
        out["RSZ_DONT_TOUCH_RX"] = analog_rx(macros)
    # Analog supply pins are left for the chip-level analog routing, so the checker would
    # call them critical disconnects. `signoff` re-checks these macros pin by pin instead.
    # ponytail: replaces the PDK list, whose sky130 entry is just conb_1; re-add any other.
    out["IGNORE_DISCONNECTED_MODULES"] = ["sky130_fd_sc_hd__conb_1"] + [
        m["block"] for m in macros if m.get("analog_supplies")
    ]
    return [f"{k}: {json.dumps(v)}" for k, v in out.items()]


def analog_rx(macros):
    return "^(" + "|".join(n for m in macros for n in m.get("analog_nets", [])) + ")$"


SIGNOFF_ZERO = [
    "magic__drc_error__count",
    "klayout__drc_error__count",
    "route__drc_errors",
    "design__lvs_error__count",
    "design__xor_difference__count",
    "magic__illegal_overlap__count",
]


def signoff(macros, run):
    run = Path(run)
    final = run / "final"
    metrics = json.loads((final / "metrics.json").read_text())
    fails = []
    for key in SIGNOFF_ZERO:
        print(f"  {key:34} {metrics.get(key)}")
        if metrics.get(key) != 0:
            fails.append(f"{key}={metrics.get(key)}")
    for key in ("timing__setup__ws", "timing__hold__ws", "design__instance__count"):
        print(f"  {key:34} {metrics.get(key)}")
    gds = sorted((final / "gds").glob("*.gds"))
    print(f"  gds                                {[f'{g.name} ({g.stat().st_size} B)' for g in gds]}")
    if not gds:
        fails.append("no GDS")

    # Macro hookup, from the powered netlist: every signal port and digital supply pin
    # connected (supplies to their declared nets), no analog supply pin on any net.
    # (Odb.ReportDisconnectedPins skips these macros, see IGNORE_DISCONNECTED_MODULES.)
    pnl = sorted((final / "pnl").glob("*.pnl.v"))
    cells = re.findall(r"^\s*(\w+)\s+(\\?\S+)\s*\((.*?)\)\s*;", strip(pnl[0].read_text()), re.M | re.S) if pnl else []
    by_inst = {inst: dict(re.findall(r"\.(\w+)\s*\(\s*([^()]*?)\s*\)", conns)) for _, inst, conns in cells}
    insts = set()
    for m in macros:
        want = dict.fromkeys(verilog_ports(need(m, "blackbox"), m["block"]), None)
        for pg in m.get("pg", []):
            want.update(zip(pg["pins"], pg["nets"]))
        for inst in m["instances"]:
            insts.add(inst)
            got = by_inst.get(inst, {})
            bad = [p for p, net in want.items() if not got.get(p) or (net and got[p] != net)]
            bad += [p for p in m.get("analog_supplies", []) if p in got]
            print(f"  {inst} pins                       {got}")
            if bad:
                fails.append(f"{inst}: wrong hookup on {bad}")

    # Analog nets: every cell pin on one must belong to a macro (no buffer, diode, tie).
    rx = re.compile(analog_rx(macros))
    if rx.pattern != "^()$":
        for cell, inst, _ in cells:
            for pin, net in by_inst[inst].items():
                if rx.match(net) and inst not in insts:
                    fails.append(f"analog net {net} on {cell} {inst}.{pin}")
        print(f"  analog nets ({rx.pattern})  touched only by macros: "
              f"{not any(f.startswith('analog net') for f in fails)}")
    print("FAIL: " + "; ".join(fails) if fails else "PASS: signoff")
    if fails:
        sys.exit(1)


def write_config(macros, cfg_path):
    cfg_path = Path(cfg_path)
    text = cfg_path.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f"macros.py: {cfg_path} has no generated block ({BEGIN!r} ... {END!r})")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    body = config_block(macros, cfg_path.resolve().parent)
    cfg_path.write_text(head + "\n".join([BEGIN, *body, END]) + tail)
    print(f"macros.py: {cfg_path}: {len(macros)} macro(s)")


if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in ("config", "sim", "check", "signoff"):
        sys.exit(__doc__)
    macros = load(sys.argv[2])
    if sys.argv[1] == "sim":
        print(" ".join(str(need(m, "behavioural")) for m in macros))
    elif sys.argv[1] == "check":
        check(macros)
    elif sys.argv[1] == "signoff":
        signoff(macros, sys.argv[3])
    else:
        check(macros)
        write_config(macros, sys.argv[3])
